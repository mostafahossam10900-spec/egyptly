// Visual review helper (not part of the test suite): `npx playwright test e2e/screens.capture.ts --project=desktop`
// Writes screenshots to test-results/screens.
import { test } from '@playwright/test'
import { futureDate, next, signUpAndConfirm, uniqueEmail } from './helpers'

test('capture wizard screens', async ({ page }, info) => {
  const dir = `test-results/screens/${info.project.name}`
  await signUpAndConfirm(page, uniqueEmail('screens'))
  await page.goto('/trips/new')
  await page.getByTestId('dest-cairo-city').click()
  await page.getByTestId('dest-luxor-city').click()
  await page.screenshot({ path: `${dir}/1-destinations.png` })
  await next(page)
  await page.getByTestId('interest-history').click()
  await page.getByTestId('interest-museums').click()
  await page.screenshot({ path: `${dir}/2-interests.png` })
  await next(page)
  await page.getByTestId('lm-tomb-of-tutankhamun').click()
  await page.getByTestId('lm-karnak').click()
  await page.getByRole('heading', { name: 'Luxor', exact: false }).first().scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${dir}/3-landmarks.png` })
  await page.getByRole('button', { name: 'Back' }).click()
  await page.getByRole('button', { name: 'Back' }).click()
  await page.getByTestId('dest-luxor-city').click()
  await page.getByTestId('removal-notice').scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${dir}/1b-removal-notice.png` })
  await page.getByRole('button', { name: 'Undo' }).click()
  await next(page)
  await next(page)
  await next(page)
  await page.getByTestId('arrival-date').fill(futureDate(10))
  await page.getByTestId('departure-date').fill(futureDate(17))
  await page.getByTestId('travelers').fill('3')
  await page.screenshot({ path: `${dir}/4-dates.png`, fullPage: true })
  await next(page)
  await page.getByTestId('type-multi_day').click()
  await page.getByTestId('comp-friends').click()
  await next(page)
  await page.getByTestId('budget-amount').fill('4500')
  await page.getByTestId('budget-currency').selectOption('EUR')
  await page.getByTestId('basis-group').click()
  await page.getByTestId('cat-accommodation').click()
  await page.screenshot({ path: `${dir}/6-budget.png`, fullPage: true })
  await next(page)
  await page.screenshot({ path: `${dir}/7-review.png`, fullPage: true })
  await page.getByTestId('wizard-submit').click()
  await page.goto('/dashboard')
  await page.screenshot({ path: `${dir}/8-dashboard.png`, fullPage: true })
  await page.evaluate(() => localStorage.setItem('egyptly.locale', 'ar'))
  await page.reload()
  await page.screenshot({ path: `${dir}/9-dashboard-ar.png`, fullPage: true })
})
