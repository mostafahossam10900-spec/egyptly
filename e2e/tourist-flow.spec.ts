test('Arabic interface is right-to-left and translated, with no horizontal scroll', async ({ page }) => {
  await page.goto('/')
  await expectNoHorizontalScroll(page)
  const menu = page.getByRole('button', { name: 'Menu' })
  if (await menu.isVisible()) await menu.click()
  await page.getByRole('button', { name: 'العربية' }).first().click()
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl')
  await expect(page.locator('html')).toHaveAttribute('lang', 'ar')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('اختر المرشد')
  await expectNoHorizontalScroll(page)

  await page.goto('/signup')
  await expect(page.getByRole('heading', { name: 'أنشئ حساب السائح' })).toBeVisible()
  await page.getByTestId('role-guide').click()
  await expect(page.getByText('حسابات المرشدين لم تُفتح بعد')).toBeVisible()
  await page.getByTestId('role-tourist').click()
  await page.getByRole('button', { name: 'إنشاء الحساب' }).click()
  await expect(page.getByText('هذا الحقل مطلوب.').first()).toBeVisible()
  await expectNoHorizontalScroll(page)

  await page.goto('/guides')
  await expect(page.getByText('لا يوجد أي مرشد مدرج أو معتمد حتى الآن.')).toBeVisible()
})

