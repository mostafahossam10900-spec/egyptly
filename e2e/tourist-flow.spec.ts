test('password reset by email works', async ({ page }) => {
  const email = uniqueEmail('reset')
  await signUpAndConfirm(page, email)
  await logout(page)
  await page.goto('/forgot-password')
  await page.getByLabel('Email').fill(email)
  await page.getByRole('button', { name: 'Send reset link' }).click()
  await expect(page.getByText(/a reset link is on its way/)).toBeVisible()
  const link = await emailLink(email, /Reset your Egyptly password/)
  await page.goto(link)
  await page.getByRole('button', { name: 'Save new password' }).click()
  await page.getByLabel('New password').fill('NewPass2026')
  await page.getByLabel('Confirm password').fill('NewPass2026')
  await page.getByRole('button', { name: 'Save new password' }).click()
  await expect(page.getByText('Your password was changed.')).toBeVisible()
  await logout(page)
  await page.goto('/login')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password').fill(PASSWORD)
  await page.getByRole('button', { name: 'Log in' }).click()
  await expect(page.getByText('Email or password is incorrect.')).toBeVisible()
  await login(page, email, 'NewPass2026')
})

