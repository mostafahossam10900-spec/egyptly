import { expect, test } from '@playwright/test'
import {
  PASSWORD, emailLink, expectNoHorizontalScroll, futureDate, login, logout, next, signUpAndConfirm, uniqueEmail,
} from './helpers'

test.describe.configure({ mode: 'serial' })

test('tourist signs up, verifies email, completes, saves and edits a trip request', async ({ page }) => {
  const email = uniqueEmail('tourist')
  await signUpAndConfirm(page, email)
  await page.getByRole('button', { name: 'Go to my trips' }).click()
  await expect(page.getByText('No trips yet')).toBeVisible()

  await page.getByRole('link', { name: 'Plan a new trip' }).first().click()

  // Step 1 — destinations (validation first)
  await expect(page.getByRole('heading', { name: 'Where do you want to go in Egypt?' })).toBeVisible()
  await next(page)
  await expect(page.getByText('Choose at least one destination.')).toBeVisible()
  await page.getByTestId('dest-cairo-city').click()
  await page.getByTestId('dest-giza-pyramids-saqqara').click()
  await page.getByTestId('dest-luxor-city').click()
  await next(page)

  // Step 2 — interests
  await expect(page.getByRole('heading', { name: 'What do you love when you travel?' })).toBeVisible()
  await expect(page.locator('[data-testid^="interest-"]')).toHaveCount(22)
  await page.getByTestId('interest-museums').click()
  await page.getByTestId('interest-ancient-egypt-archaeology').click()
  await next(page)

  // Step 3 — landmarks (sub-sites nested; reasons shown)
  await expect(page.getByRole('heading', { name: 'Choose landmarks' })).toBeVisible()
  await expect(page.getByText(/not verified yet/).first()).toBeVisible()
  await page.getByTestId('lm-egyptian-museum-tahrir').click()
  await page.getByTestId('lm-great-sphinx').click()
  await page.getByTestId('lm-karnak').click()
  await page.getByTestId('lm-tomb-of-tutankhamun').click()
  await expect(page.getByText('4 landmarks selected')).toBeVisible()
  await next(page)

  // Step 4 — dates: invalid input handled
  await page.getByTestId('arrival-date').fill(futureDate(20))
  await page.getByTestId('departure-date').fill(futureDate(15))
  await page.getByTestId('travelers').fill('0')
  await next(page)
  await expect(page.getByText('Departure must be on or after the arrival date.')).toBeVisible()
  await expect(page.getByText('Enter a whole number from 1 to 100.')).toBeVisible()
  await page.getByTestId('departure-date').fill(futureDate(29))
  await page.getByTestId('travelers').fill('5')
  await page.getByTestId('departure-available').check()
  await expect(page.getByTestId('duration')).toContainText('Nights in Egypt: 9')
  await expect(page.getByTestId('duration')).toContainText('Days you can visit places: 9')
  await next(page)

  // Step 5 — type & companions (Day trip conflicts with multi-day dates)
  await page.getByTestId('type-day_trip').click()
  await page.getByTestId('comp-family').click()
  await next(page)
  await expect(page.getByText(/A day trip starts and ends on the same date/)).toBeVisible()
  await page.getByTestId('type-multi_day').click()
  await next(page)

  // Step 6 — budget validation
  await page.getByTestId('budget-amount').fill('-5')
  await next(page)
  await expect(page.getByText('Enter a number, for example 5000 or 5000.50.')).toBeVisible()
  await expect(page.getByText('Choose a currency.')).toBeVisible()
  await page.getByTestId('budget-amount').fill('5000')
  await page.getByTestId('budget-currency').selectOption('USD')
  await page.getByTestId('basis-group').click()
  await page.getByTestId('cat-accommodation').click()
  await page.getByTestId('cat-entry_tickets').click()
  await expect(page.getByText(/about \$1,000\.00 per person/)).toBeVisible()
  await next(page)

  // Step 7 — review: request, not itinerary/booking
  await expect(page.getByRole('heading', { name: 'Review your trip request' })).toBeVisible()
  await expect(page.getByText('This is a trip request summary. It is not an itinerary, a price quote or a booking.').first()).toBeVisible()
  await page.getByTestId('wizard-submit').click()
  await expect(page.getByText('Trip request saved.')).toBeVisible()
  const tripUrl = page.url()

  // Survives refresh
  await page.reload()
  await expect(page.getByText('Tomb of Tutankhamun (KV62)')).toBeVisible()

  // Survives logout + login
  await logout(page)
  await login(page, email)
  await expect(page.getByTestId('trip-list')).toContainText('Cairo · Giza — Pyramids, Saqqara & Dahshur · Luxor')
  await expect(page.getByText('Request saved')).toBeVisible()

  // Edit: removing Luxor removes its landmarks visibly
  await page.goto(tripUrl.replace(/\/?$/, '') + '/edit?step=1')
  await page.getByTestId('dest-luxor-city').click()
  const notice = page.getByTestId('removal-notice')
  await expect(notice).toContainText('Karnak Temple Complex')
  await expect(notice).toContainText('Tomb of Tutankhamun (KV62)')
  // Undo restores, then remove again
  await notice.getByRole('button', { name: 'Undo' }).click()
  await expect(notice).toBeHidden()
  await page.getByTestId('dest-luxor-city').click()
  await next(page)
  await expect(page.getByText('You changed a saved request, so it is back to draft.')).toBeVisible()
  await page.goto(tripUrl.replace(/\/?$/, '') + '/edit?step=7')
  await expect(page.getByText('Karnak Temple Complex')).toHaveCount(0)
  await page.getByTestId('wizard-submit').click()
  await expect(page.getByText('Trip request saved.')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Egyptian Museum, Tahrir')).toBeVisible()
  await expect(page.getByText('Karnak Temple Complex')).toHaveCount(0)

  // Another user cannot open this trip
  await logout(page)
  const other = uniqueEmail('other')
  await signUpAndConfirm(page, other, 'Omar', 'Ali')
  await page.goto(tripUrl)
  await expect(page.getByText('This trip does not exist or belongs to another account.')).toBeVisible()
  await page.goto('/dashboard')
  await expect(page.getByText('No trips yet')).toBeVisible()
})

