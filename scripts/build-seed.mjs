// Generates supabase/seed.sql from reference-data/landmarks.mjs.
// Idempotent: every statement is an upsert, so it can be re-run against any database.
// Usage: npm run seed:build   (then `npx supabase db reset` locally, or run seed.sql remotely)
import { writeFileSync } from 'node:fs';
import { governorates, interests, SOURCE_DOCUMENT } from '../reference-data/landmarks.mjs';
import { flattenReferenceData, validateReferenceData } from '../reference-data/flatten.mjs';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => (a && a.length ? `array[${a.map(q).join(',')}]::text[]` : `'{}'::text[]`);

const data = flattenReferenceData(governorates);
const problems = validateReferenceData(data, interests);
if (problems.length) {
  console.error('Reference data is invalid:\n- ' + problems.join('\n- '));
  process.exit(1);
}

const out = [];
out.push(`-- GENERATED by scripts/build-seed.mjs from ${SOURCE_DOCUMENT}. Do not edit by hand.`);
out.push('-- Landmark operational fields (coordinates, hours, tickets, images) are intentionally left NULL = unknown.');
out.push('begin;');

for (const g of data.governorates) {
  const sources = JSON.stringify(g.sources.map(([label_ar, url]) => ({ label_ar, url })));
  out.push(`insert into public.governorates (slug, name_ar, name_en, note_ar, discussion_order, sources) values (${q(g.slug)}, ${q(g.name_ar)}, ${q(g.name_en)}, ${q(g.note_ar)}, ${g.discussion_order}, ${q(sources)}::jsonb)
  on conflict (slug) do update set name_ar = excluded.name_ar, name_en = excluded.name_en, note_ar = excluded.note_ar, discussion_order = excluded.discussion_order, sources = excluded.sources;`);
}
for (const d of data.destinations) {
  out.push(`insert into public.destinations (slug, governorate_slug, name_ar, name_en, sort_order) values (${q(d.slug)}, ${q(d.governorate_slug)}, ${q(d.name_ar)}, ${q(d.name_en)}, ${d.sort_order})
  on conflict (slug) do update set governorate_slug = excluded.governorate_slug, name_ar = excluded.name_ar, name_en = excluded.name_en, sort_order = excluded.sort_order;`);
}
// Two passes so parents exist before children reference them.
for (const pass of ['insert', 'parents']) {
  for (const l of data.landmarks) {
    if (pass === 'insert') {
      out.push(`insert into public.landmarks (slug, destination_slug, section_ar, section_en, name_ar, name_en, type, flags, sort_order) values (${q(l.slug)}, ${q(l.destination_slug)}, ${q(l.section_ar)}, ${q(l.section_en)}, ${q(l.name_ar)}, ${q(l.name_en)}, ${q(l.type)}::public.landmark_type, ${arr(l.flags)}, ${l.sort_order})
  on conflict (slug) do update set destination_slug = excluded.destination_slug, section_ar = excluded.section_ar, section_en = excluded.section_en, name_ar = excluded.name_ar, name_en = excluded.name_en, type = excluded.type, flags = excluded.flags, sort_order = excluded.sort_order;`);
    } else if (l.parent_slug) {
      out.push(`update public.landmarks set parent_slug = ${q(l.parent_slug)} where slug = ${q(l.slug)};`);
    }
  }
}
for (const [i, [slug, en, ar]] of interests.entries()) {
  out.push(`insert into public.interests (slug, name_en, name_ar, sort_order) values (${q(slug)}, ${q(en)}, ${q(ar)}, ${i + 1})
  on conflict (slug) do update set name_en = excluded.name_en, name_ar = excluded.name_ar, sort_order = excluded.sort_order;`);
}
out.push('commit;', '');

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'), 'utf8');
console.log(`seed.sql written: ${data.governorates.length} governorates, ${data.destinations.length} destinations, ${data.landmarks.length} landmarks, ${interests.length} interests`);
