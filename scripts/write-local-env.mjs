// Writes .env.local for the Vite app from the LOCAL Supabase stack (`npx supabase status`).
// .env.local is git-ignored. Only the public anon/publishable key is written — never the service key.
import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const out = execSync('npx supabase status -o env', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] })
const vars = Object.fromEntries(
  out.split(/\r?\n/).map((l) => /^([A-Z_]+)="?(.*?)"?$/.exec(l)).filter(Boolean).map((m) => [m[1], m[2]]),
)
const url = vars.API_URL
const anon = vars.ANON_KEY ?? vars.PUBLISHABLE_KEY
if (!url || !anon) {
  console.error('Could not read API_URL / ANON_KEY from `supabase status`. Is the local stack running (npx supabase start)?')
  process.exit(1)
}
writeFileSync(
  new URL('../.env.local', import.meta.url),
  `# Generated by scripts/write-local-env.mjs for the LOCAL Supabase stack.\nVITE_SUPABASE_URL=${url}\nVITE_SUPABASE_ANON_KEY=${anon}\nVITE_SITE_URL=http://localhost:5173\n`,
)
console.log(`.env.local written for ${url}`)
